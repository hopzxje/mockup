// Helper to generate 36 apartments with assets
export function generateInitialApartmentsAndAssets(): { apartments: Apartment[]; assets: Asset[] } {
  const apartments: Apartment[] = [];
  const assets: Asset[] = [];

  const buildingSpecs = [
    { bldId: "bld-1", bldName: "StayHub Central - Quận 1", basePrice: 5500000, baseArea: 32 },
    { bldId: "bld-2", bldName: "StayHub Landmark - Bình Thạnh", basePrice: 4800000, baseArea: 30 },
    { bldId: "bld-3", bldName: "StayHub Westlake - Tây Hồ", basePrice: 6200000, baseArea: 35 },
  ];

  buildingSpecs.forEach((bld) => {
    for (let floor = 1; floor <= 3; floor++) {
      for (let roomIdx = 1; roomIdx <= 4; roomIdx++) {
        const roomNum = floor * 100 + roomIdx;
        const roomCode = `${roomNum}`;
        const aptId = `apt-${bld.bldId}-${roomCode}`;
        
        let status: Apartment["status"] = "Trống";
        let residentId: string | undefined;
        let residentName: string | undefined;
        let contractId: string | undefined;

        // Associate demo residents
        if (bld.bldId === "bld-1" && roomCode === "101") {
          status = "Đang thuê";
          residentId = "res-1";
          residentName = "Lê Thị Thu Thảo";
          contractId = "ctr-2026-001";
        } else if (bld.bldId === "bld-1" && roomCode === "202") {
          status = "Đang thuê";
          residentId = "res-2";
          residentName = "Nguyễn Văn An";
          contractId = "ctr-2026-002";
        } else if (bld.bldId === "bld-2" && roomCode === "303") {
          status = "Đang thuê";
          residentId = "res-3";
          residentName = "Trần Quang Huy";
          contractId = "ctr-2026-003";
        } else if (bld.bldId === "bld-3" && roomCode === "102") {
          status = "Đang thuê";
          residentId = "res-4";
          residentName = "Vũ Mai Phương";
          contractId = "ctr-2026-004";
        } else if (bld.bldId === "bld-1" && roomCode === "103") {
          status = "Đã giữ chỗ"; // Contract pending approval
        } else if (bld.bldId === "bld-2" && roomCode === "104") {
          status = "Bảo trì"; // Under maintenance
        } else if (bld.bldId === "bld-3" && roomCode === "304") {
          status = "Ngừng sử dụng";
        }

        const area = bld.baseArea + (roomIdx % 2 === 0 ? 3 : 0);
        const refPrice = bld.basePrice + (floor - 1) * 200000;

        const bldCodePrefix = bld.bldId === "bld-1" ? "SH-CENTRAL" : bld.bldId === "bld-2" ? "SH-LANDMARK" : "SH-WESTLAKE";
        apartments.push({
          id: aptId,
          buildingId: bld.bldId,
          buildingName: bld.bldName,
          roomCode,
          floor,
          areaSqm: area,
          referencePrice: refPrice,
          currentPrice: refPrice,
          status,
          description: `Phòng ${roomCode} tầng ${floor}, ban công thoáng, đầy đủ nội thất cao cấp.`,
          currentContractId: contractId,
          currentResidentId: residentId,
          currentResidentName: residentName,
          assetCount: initialAssetTypes.length,
          electricityMeterCode: `EM-${bldCodePrefix}-${roomCode}`,
          waterMeterCode: `WM-${bldCodePrefix}-${roomCode}`,
          initialElectricityIndex: 0,
          initialWaterIndex: 0,
          createdAt: "2025-01-20T08:00:00Z",
        });

        // Predefined assets auto-generated with room
        initialAssetTypes.forEach((at, idx) => {
          let cond: Asset["condition"] = "Tốt";
          if (aptId === "apt-bld-2-104" && at.code === "AC") cond = "Đang sửa";
          if (aptId === "apt-bld-1-202" && at.code === "AC") cond = "Hư hỏng"; // triggers maintenance request

          assets.push({
            id: `ast-${aptId}-${at.code.toLowerCase()}`,
            apartmentId: aptId,
            apartmentCode: roomCode,
            buildingId: bld.bldId,
            assetTypeId: at.id,
            assetTypeName: at.name,
            name: `${at.name} - P.${roomCode}`,
            code: `${bld.bldId.toUpperCase()}-${roomCode}-${at.code}`,
            serialNumber: `SN-${bld.bldId.slice(-1)}${roomCode}-${1000 + idx}`,
            condition: cond,
            installedDate: "2025-01-20",
            lastCheckedAt: "2026-09-01T09:00:00Z",
            lastUpdatedBy: "Phạm Tuấn Anh (Staff)",
            notes: "Kiểm tra định kỳ hoạt động bình thường",
          });
        });
      }
    }
  });

  return { apartments, assets };
}

